-- Supabase数据库结构
-- 创建作品表

-- 创建works表
CREATE TABLE IF NOT EXISTS works (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    brief TEXT NOT NULL,
    description TEXT NOT NULL,
    category TEXT[] NOT NULL,
    cover TEXT NOT NULL,
    ratio TEXT DEFAULT '16:9' CHECK (ratio IN ('16:9', '4:3')),
    "order" INTEGER NOT NULL DEFAULT 0,
    images TEXT[] DEFAULT '{}',
    videos TEXT[] DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 创建索引
CREATE INDEX IF NOT EXISTS works_order_idx ON works("order");
CREATE INDEX IF NOT EXISTS works_created_at_idx ON works(created_at DESC);

-- 启用行级安全
ALTER TABLE works ENABLE ROW LEVEL SECURITY;

-- 创建策略 - 允许所有人读取（用于前端展示）
CREATE POLICY "允许所有人读取作品"
    ON works
    FOR SELECT
    USING (true);

-- 创建策略 - 仅允许认证用户修改（用于后台管理）
CREATE POLICY "允许认证用户插入作品"
    ON works
    FOR INSERT
    WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "允许认证用户更新作品"
    ON works
    FOR UPDATE
    USING (auth.uid() IS NOT NULL);

CREATE POLICY "允许认证用户删除作品"
    ON works
    FOR DELETE
    USING (auth.uid() IS NOT NULL);

